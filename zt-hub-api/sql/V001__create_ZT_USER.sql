CREATE TABLE ZT_USER (
    id UNIQUEIDENTIFIER NOT NULL CONSTRAINT PK_ZT_USER PRIMARY KEY DEFAULT NEWID(),
    username NVARCHAR(64) NOT NULL,
    email NVARCHAR(128) NOT NULL,
    first_name NVARCHAR(100) NOT NULL,
    last_name NVARCHAR(100) NOT NULL,
    password_hash NVARCHAR(100) NOT NULL,
    role_codes NVARCHAR(MAX) NOT NULL CONSTRAINT DF_ZT_USER_ROLE_CODES DEFAULT N'["USER"]',
    status NVARCHAR(16) NOT NULL CONSTRAINT DF_ZT_USER_STATUS DEFAULT N'ACTIVE',
    last_login_at DATETIME2 NULL,
    last_login_ip NVARCHAR(64) NULL,
    created_at DATETIME2 NOT NULL CONSTRAINT DF_ZT_USER_CREATED_AT DEFAULT GETDATE(),
    updated_at DATETIME2 NOT NULL CONSTRAINT DF_ZT_USER_UPDATED_AT DEFAULT GETDATE(),
    CONSTRAINT UQ_ZT_USER_USERNAME UNIQUE (username),
    CONSTRAINT UQ_ZT_USER_EMAIL UNIQUE (email),
    CONSTRAINT CK_ZT_USER_STATUS CHECK (status IN (N'ACTIVE', N'INACTIVE')),
    CONSTRAINT CK_ZT_USER_ROLE_CODES_JSON CHECK (ISJSON(role_codes) = 1)
);
CREATE INDEX IX_ZT_USER_STATUS ON ZT_USER (status);
