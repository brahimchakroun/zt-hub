CREATE TABLE ZT_PASSWORD_RESET (
    id BIGINT IDENTITY(1,1) NOT NULL CONSTRAINT PK_ZT_PASSWORD_RESET PRIMARY KEY,
    user_id UNIQUEIDENTIFIER NOT NULL,
    token_hash CHAR(64) NOT NULL,
    expires_at DATETIME2 NOT NULL,
    consumed_at DATETIME2 NULL,
    ip NVARCHAR(64) NULL,
    created_at DATETIME2 NOT NULL CONSTRAINT DF_ZT_PASSWORD_RESET_CREATED_AT DEFAULT GETDATE(),
    CONSTRAINT UQ_ZT_PASSWORD_RESET_TOKEN UNIQUE (token_hash),
    CONSTRAINT FK_ZT_PASSWORD_RESET_USER FOREIGN KEY (user_id) REFERENCES ZT_USER (id) ON DELETE CASCADE
);
CREATE INDEX IX_ZT_PASSWORD_RESET_USER ON ZT_PASSWORD_RESET (user_id);
