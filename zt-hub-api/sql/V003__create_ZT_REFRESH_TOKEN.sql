CREATE TABLE ZT_REFRESH_TOKEN (
    id BIGINT IDENTITY(1,1) NOT NULL CONSTRAINT PK_ZT_REFRESH_TOKEN PRIMARY KEY,
    user_id UNIQUEIDENTIFIER NOT NULL,
    token_hash CHAR(64) NOT NULL,
    expires_at DATETIME2 NOT NULL,
    revoked_at DATETIME2 NULL,
    created_at DATETIME2 NOT NULL CONSTRAINT DF_ZT_REFRESH_TOKEN_CREATED_AT DEFAULT GETDATE(),
    CONSTRAINT UQ_ZT_REFRESH_TOKEN_HASH UNIQUE (token_hash),
    CONSTRAINT FK_ZT_REFRESH_TOKEN_USER FOREIGN KEY (user_id) REFERENCES ZT_USER (id) ON DELETE CASCADE
);
CREATE INDEX IX_ZT_REFRESH_TOKEN_USER ON ZT_REFRESH_TOKEN (user_id);
