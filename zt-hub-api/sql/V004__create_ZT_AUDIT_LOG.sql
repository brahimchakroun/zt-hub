CREATE TABLE ZT_AUDIT_LOG (
    id BIGINT IDENTITY(1,1) NOT NULL CONSTRAINT PK_ZT_AUDIT_LOG PRIMARY KEY,
    user_id UNIQUEIDENTIFIER NULL,
    action NVARCHAR(32) NOT NULL,
    resource NVARCHAR(128) NULL,
    resource_id NVARCHAR(128) NULL,
    before_json NVARCHAR(MAX) NULL,
    after_json NVARCHAR(MAX) NULL,
    ip NVARCHAR(64) NULL,
    user_agent NVARCHAR(512) NULL,
    created_at DATETIME2 NOT NULL CONSTRAINT DF_ZT_AUDIT_LOG_CREATED_AT DEFAULT GETDATE(),
    CONSTRAINT FK_ZT_AUDIT_LOG_USER FOREIGN KEY (user_id) REFERENCES ZT_USER (id)
);
CREATE INDEX IX_ZT_AUDIT_LOG_CREATED_AT ON ZT_AUDIT_LOG (created_at);
CREATE INDEX IX_ZT_AUDIT_LOG_USER ON ZT_AUDIT_LOG (user_id);
