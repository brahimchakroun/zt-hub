CREATE TABLE ZT_ROLE_PAGE (
    role_code NVARCHAR(64) NOT NULL,
    page_code NVARCHAR(128) NOT NULL,
    CONSTRAINT PK_ZT_ROLE_PAGE PRIMARY KEY (role_code, page_code),
    CONSTRAINT FK_ZT_ROLE_PAGE_ROLE FOREIGN KEY (role_code) REFERENCES ZT_ROLE (code),
    CONSTRAINT FK_ZT_ROLE_PAGE_PAGE FOREIGN KEY (page_code) REFERENCES ZT_PAGE (page_code)
);
CREATE INDEX IX_ZT_ROLE_PAGE_PAGE_CODE ON ZT_ROLE_PAGE (page_code);