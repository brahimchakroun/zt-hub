CREATE TABLE ZT_PERMISSION (
    permission_code NVARCHAR(128) NOT NULL CONSTRAINT PK_ZT_PERMISSION PRIMARY KEY,
    label NVARCHAR(128) NOT NULL,
    group_name NVARCHAR(64) NULL,
    display_order INT NOT NULL CONSTRAINT DF_ZT_PERMISSION_DISPLAY_ORDER DEFAULT 0,
    active BIT NOT NULL CONSTRAINT DF_ZT_PERMISSION_ACTIVE DEFAULT 1,
    description NVARCHAR(500) NULL
);

CREATE TABLE ZT_ROLE_PERMISSION (
    role_code NVARCHAR(64) NOT NULL,
    permission_code NVARCHAR(128) NOT NULL,
    CONSTRAINT PK_ZT_ROLE_PERMISSION PRIMARY KEY (role_code, permission_code),
    CONSTRAINT FK_ZT_ROLE_PERMISSION_ROLE FOREIGN KEY (role_code) REFERENCES ZT_ROLE (code),
    CONSTRAINT FK_ZT_ROLE_PERMISSION_PERMISSION FOREIGN KEY (permission_code) REFERENCES ZT_PERMISSION (permission_code)
);
CREATE INDEX IX_ZT_ROLE_PERMISSION_PERMISSION_CODE ON ZT_ROLE_PERMISSION (permission_code);