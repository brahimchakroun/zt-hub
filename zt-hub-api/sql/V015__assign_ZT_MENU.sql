CREATE TABLE ZT_MENU (
    menu_code varchar(128) NOT NULL CONSTRAINT PK_ZT_MENU PRIMARY KEY,
    label varchar(128) NOT NULL,
    url_root varchar(128) NOT NULL,
    display_order INT NOT NULL CONSTRAINT DF_ZT_MENU_DISPLAY_ORDER DEFAULT 0,
    active BIT NOT NULL CONSTRAINT DF_ZT_MENU_ACTIVE DEFAULT 1
);

