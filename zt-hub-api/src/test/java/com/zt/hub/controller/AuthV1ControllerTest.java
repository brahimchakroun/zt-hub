    @Test
    void duplicateRegistrationReturnsFieldConflict() throws Exception {
        mvc.perform(post("/api/v1/auth/register").contentType(MediaType.APPLICATION_JSON)
                .content("""{"username":"dupe","email":"dupe@example.com","password":"secret1","firstName":"Dupe","lastName":"User"}"""));
        mvc.perform(post("/api/v1/auth/register").contentType(MediaType.APPLICATION_JSON)
                        .content("""{"username":"dupe","email":"other@example.com","password":"secret1","firstName":"Dupe","lastName":"User"}"""))
                .andExpect(status().isConflict()).andExpect(jsonPath("$.error.code").value("user.username.duplicate"))
                .andExpect(jsonPath("$.error.field").value("username"));
    }

